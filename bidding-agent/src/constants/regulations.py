@dataclass(frozen=True)
class RegulationArticle:
    """一条法规原文及其定位信息。

    字段语义（`regulation_store` 的 payload 与检索结果都依赖它们）：
        law        法规全称，与 `LAW_*` 常量一致，用作去重键的一半
        law_short  简称，供前端窄栏展示与日志
        article    条号原文（"第四十三条" / "第二十六条"），检索结果定位用
        text       条文原文（可含多款，换行分隔；节选见模块 docstring 第 4 条）
        topics     主题标签，检索加权与合规分类的锚点，**必须真实反映内容**
        level      效力层级，受控取值见 `LEVEL_*`
        effective  施行日期 YYYY-MM-DD，不确定时为空串
    """

    law: str
    law_short: str
    article: str
    text: str
    topics: tuple[str, ...]
    level: str
    effective: str

    @property
    def key(self) -> str:
        """稳定去重键：`法规全称|条号`。

        入库 point id 与单测去重都基于它——**同一部法规的条号不可能重复**，
        因此在条文增删后仍然稳定（不会因为列表顺序变化而错位）。
        """
        return f"{self.law}|{self.article}"

    def to_payload(self) -> dict:
        """转成 Qdrant payload。列表而非元组：Qdrant 不接受 tuple。"""
        return {
            "law": self.law,
            "law_short": self.law_short,
            "article": self.article,
            "text": self.text,
            "topics": list(self.topics),
            "level": self.level,
            "effective": self.effective,
        }


def _a(
    law: str,
    law_short: str,
    article: str,
    text: str,
    topics: tuple[str, ...],
    level: str,
    effective: str,
) -> RegulationArticle:
    """构造一条条文，按 `law` 自动补全 `doc_number`/来源所需的稳定字段。

    紧凑写法是为了让"一眼能看出收了哪些条"——147 条若逐条写全关键字参数，
    文件会长到难以校读。
    """
    return RegulationArticle(
        law=law,
        law_short=law_short,
        article=article,
        text=text,
        topics=topics,
        level=level,
        effective=effective,
    )


