REGULATIONS: tuple[RegulationArticle, ...] = tuple(
    _TB + _TB_REG + _GP + _GP_REG + _MOF87 + _MOF74 + _NDRC16 + _FAIR + _BIZ
)
"""全部条文。顺序：法律 → 实施条例 → 政府采购 → 部门规章 → 规范性文件。

顺序**只影响展示**：入库 point id 由 `RegulationArticle.key` 决定，
因此调整本元组的顺序不会造成重复入库。
"""

# 效力层级的展示顺序（统计输出按此排序，保证多次运行结果一致）
LEVEL_ORDER: tuple[str, ...] = (
    LEVEL_LAW,
    LEVEL_REGULATION,
    LEVEL_RULE,
    LEVEL_NORMATIVE,
)

# 做过节选（text 里含 `……`）的条文键，与 `topics` 里的 "节选" 标记互为印证。
# 显式列出而不是从文本里扫 `……`：这样"新增节选"必须同时改代码，
# 不会出现悄悄截断一段原文却无人察觉的情况（单测双向校验，见 tests/test_regulations.py）。
ABRIDGED_KEYS: frozenset[str] = frozenset(
    {
        f"{LAW_MOF87}|第二十条",
        f"{LAW_MOF87}|第七十八条",
    }
)

# 节选标记（与 ABRIDGED_KEYS 配套）
TOPIC_ABRIDGED = "节选"

# 裁剪标记行的字面量：**整行**只有这个省略号才算"我方裁剪"。
# 行内的省略号（如财政部令第87号第五十五条 `F1×A1＋……＋Fn×An`）是官方原文自带的，
# 不表示节选——这个区分由 abridged_marker_keys() 负责，单测依赖它。
ABRIDGED_MARKER = "……"


def abridged_marker_keys() -> set[str]:
    """返回带"裁剪标记行"的条文键（`ABRIDGED_KEYS` 的运行时复算）。

    判定标准：`text` 中**存在整行仅为 `……`** 的行。
    与"文本里含省略号"不是一回事：公式、顿号列举里的行内省略号属原文，
    若把两者混为一谈，会把完整条文误判为节选（开发时确实踩过这个坑）。
    """
    return {
        item.key
        for item in REGULATIONS
        if any(line.strip() == ABRIDGED_MARKER for line in item.text.splitlines())
    }


def all_articles() -> tuple[RegulationArticle, ...]:
    """返回全部条文（供 `regulation_store` 与脚本使用）。"""
    return REGULATIONS


def articles_by_law() -> dict[str, list[RegulationArticle]]:
    """按法规全称分组，保持语料定义顺序。"""
    grouped: dict[str, list[RegulationArticle]] = {}
    for item in REGULATIONS:
        grouped.setdefault(item.law, []).append(item)
    return grouped


def duplicate_keys() -> list[str]:
    """返回重复的 `law|article` 键（正常应为空；单测用于守卫语料质量）。"""
    counter = Counter(item.key for item in REGULATIONS)
    return sorted(key for key, count in counter.items() if count > 1)


def corpus_stats() -> dict:
    """语料统计：法规数、条文数、按效力层级分布、按主题分布。

    返回值结构（单测依赖，改动需同步 `tests/test_regulations.py`）：

        {
          "articles": int,                  # 条文总数
          "laws": int,                      # 涉及法规数
          "law_names": list[str],           # 法规全称（按语料顺序）
          "by_level": {层级: 条数},          # 按效力层级，按 LEVEL_ORDER 排序
          "by_law": {法规全称: 条数},        # 按法规
          "by_law_short": {简称: 条数},
          "topics": {主题: 条数},            # 按主题，降序（同数按主题名升序）
          "topic_total": int,               # 主题出现的总次数（一条多主题会重复计数）
          "law_count": int,                 # 同 laws，便于调用方按需取用
          "level_count": int,               # 出现过的层级种类数
          "laws_with_dates": int,           # 有施行日期的法规数
        }
    """
    by_level: Counter[str] = Counter(item.level for item in REGULATIONS)
    by_law: Counter[str] = Counter(item.law for item in REGULATIONS)
    topics: Counter[str] = Counter(topic for item in REGULATIONS for topic in item.topics)

    # 层级分布：先按受控顺序，再补上不在受控列表里的（防御性，便于发现拼错的层级）
    ordered_levels: dict[str, int] = {lv: by_level[lv] for lv in LEVEL_ORDER if by_level[lv]}
    for level, count in sorted(by_level.items()):
        ordered_levels.setdefault(level, count)

    return {
        "articles": len(REGULATIONS),
        "laws": len(by_law),
        "law_count": len(by_law),
        "law_names": list(by_law.keys()),
        "by_level": ordered_levels,
        "level_count": len(by_level),
        "by_law": dict(by_law),
        "by_law_short": {
            short: sum(1 for item in REGULATIONS if item.law_short == short)
            for short in dict.fromkeys(item.law_short for item in REGULATIONS)
        },
        "topics": dict(sorted(topics.items(), key=lambda kv: (-kv[1], kv[0]))),
        "topic_total": sum(topics.values()),
        "laws_with_dates": len({item.law for item in REGULATIONS if item.effective}),
    }
