# 深度思考回退注入：未配置思考模型时，用提示词引导模型先推理再作答。
#
# ★ 为什么写成"三步固定结构"而不是一句"请逐步推理"
# --------------------------------------------
# 原实现是一句话：「请在回答前先逐步推理：拆解问题、核对已获得的工具结果
# 是否充分、判断是否需要补充检索，确认后再给出最终结论。」
#
# 实测问题：**"逐步推理"太抽象**，模型（尤其非推理模型）往往直接给结论，
# 或写一段与回答无实质差别的"我分析了以下方面"。给出**可执行的步骤与每步
# 产出要求**，才有稳定的效果——这也是本注入存在的唯一理由（没有推理模型时
# 靠它拉高分析深度）。
#
# ★ 为什么明确写"推理不输出到正文"
# ----------------------------
# 该路径没有独立的思维链通道（`chat_stream_thinking` 不可用），推理与正文
# 会混在同一个流里。若不约束，用户看到的是"让我想想…首先…其次…"再给结论，
# 正文变得冗长。推理模型那条路径则天然分离（reasoning_content 单独成流）。
#
# ★ 为什么强调"以工具结果为依据"
# --------------------------
# 前置的系统提示已要求"先调工具再回答"，但深度分析时模型容易顺着常识
# 展开长篇推演，反而淡化实际检索到的数据。本项目最不能接受的就是编造，
# 故在注入里再强调一次"有工具结果时以其为依据"。
DEEP_THINKING_INJECT = """\

## 本轮启用深度思考，请按以下三步组织你的分析

**第一步 · 拆解问题**
把用户的问题拆成若干需要分别回答的子问题，明确每个子问题需要哪类依据
（法规条文 / 知识库问答 / 图谱关系 / 业务数据 / 联网信息）。若问题本身
很简单，直接说明"无需拆解"并进入第二步——不要为凑结构而空谈。

**第二步 · 多角度分析**
逐个分析上一步拆出的子问题，每个结论都要给出依据来源。
- 有工具结果时，**以其为依据**；工具结果不足或为空，如实说明缺什么，
  不要用常识补齐。
- 涉及法规、金额、时间、资质等硬性条款时，指出其适用条件与例外。
- 存在多种解读或口径不一致时，把分歧摆出来，而不是只取其一。

**第三步 · 给出结论**
先给明确结论（可执行、可判断），再列出结论所依赖的关键依据与前提条件。
若某处依据不足，明确写出"这一点依据不足，需人工核实"，不要含糊带过。

推理与自我检查的过程不必输出到正文中——正文只保留拆解结果、
分析要点与最终结论。"""

