def as_pairs() -> list[tuple[str, tuple[str, ...]]]:
    """给检索评测用的 `[(query, keys)]`（与 `retrieval_precision.TOPICS` 同形）。

    **已剔除知识库缺口题**（见 `KNOWN_CORPUS_GAPS`）：
    库里没有对应文档的题，测的是"知识库覆盖"而不是"检索能力"，
    混进来会把"该补语料"误报成"召回退化"。
    """
    return [
        (question, keys)
        for _label, question, keys in HARD_TOPICS
        if question not in KNOWN_CORPUS_GAPS
    ]


#: 库内**没有**对应文档的题（实测全量扫语料核对过，见 `logs/_corpus_truth.py`）。
#:
#: ★ 为什么必须标出来（实测踩到）
#: --------------------------
#: 严格判据下 14 题里有 2 题"前 5 条全不切题"。全量扫一遍语料才发现成因不同：
#:
#:     招标文件卖得太贵有规定吗？   库里**有** 3 篇含"工本费/收取费用" → 真·召回失手
#:     开标时投标人能进现场看吗？   库里**一篇都没有**（缺《招标投标法》第三十四/三十五条）
#:                                 → 知识库缺口，不是检索的问题
#:
#: 把后者算作"召回退化"会指向错误的修法（去调检索参数，而其实该补语料）。
#: 故从指标里剔除，但**在 note 里报出条数** —— 不隐藏，只是不混为一谈。
#:
#: ⚠️ 语料更新后要重新核对：补进文档后应把该题从这里移除
#: （重跑 `logs/_corpus_truth.py` 即可看到命中数从 0 变成 ≥1）。
KNOWN_CORPUS_GAPS: frozenset[str] = frozenset({
    "开标的时候投标人能进现场看吗？",
})


def corpus_gap_note() -> str:
    """给报告 note 用的一句话（无缺口时返回空串）。"""
    if not KNOWN_CORPUS_GAPS:
        return ""
    return (
        f"另有 {len(KNOWN_CORPUS_GAPS)} 题**库内无据**（知识库缺口，不计入检索指标）："
        + "、".join(sorted(KNOWN_CORPUS_GAPS))
    )


