"""难例检索主题集：**真实问法**下的召回/排序测量。

★ 为什么必须单独一套（现有评测集测不出真实差距）
==========================================
`retrieval_precision.TOPICS`（18 主题）与知识库**高度重叠**：实测
首位切题率 0.9444、首个切题位次 1.06 —— 已经贴着天花板，
**分辨不出任何排序优化的好坏**（0.9444 → 1.0 只剩 1 题的余量）。

而真实用户不会用词条里的原话提问。用 14 条真实问法实测：
    评测集（原话问法）  首位切题率 0.9444   位次 1.06
    本集（真实问法）    首位切题率 0.7857   位次 1.43   ← 差 16 个百分点
差距全在**排序**上（两集的"前 5 条全不切题"都是 0，即召回本身没问题）。

本集的价值不是"再刷一个高分"，而是：
    ① 让排序改动的**收益与代价都能被看见**（实测已用它否掉了两个方案：
       精排开启、纯余弦排序 —— 它们在原评测集上分别是"变好"与"看不出差别"）
    ② 给门禁一条**不在天花板**的指标，退化时真的会红

★ 判据怎么定的（避免"挑对自己有利的标准"）
=====================================
每题给出 2~3 个关键词，**命中任一即算该文档切题**，与原评测集同一口径
（不引入新判据，否则两套分数不可比）。关键词取自条文原文的**法定表述**
（"退还""串通""订立合同"），而问题用的是口语/间接说法 —— 这正是要测的落差。

★ 已知局限与实测数字（30 题版本）
==========================
    · **占比**（`python eval/run_all.py --suites retrieval` 实测）：
          首位切题率 0.6667（20/30）｜首个切题位次 1.40｜前 5 全不切题 0.1667（5/30）
      对照同口径的评测集：0.9444 / 1.06 / 0.0 —— 真实问法下**差 28 个百分点**
    · **样本量**：30 题下 1 题 = 3.3 个百分点。实测两个定向修正
      （dense#1 保送、sentence 权重 0.7→0.85）各只能挽回 1 题 —— **落在噪声内，
      故未采纳**。要检测这个量级的改进，题目需再翻几倍（100+）
    · 判据是关键词匹配，会漏掉"语义切题但用词不同"的文档（对两套集一视同仁）
    · 题目由人工编写，**可能带有编写者的用词偏好**；新增题目应保持同一风格，
      且必须先用 `python -m eval.corpus_audit` 确认"库内有据"（否则测的是覆盖而非检索）

★ 失败归因（实测，2026-10-16）
======================
5 道全不切题的题，按"支持文档在候选池的位次"分类（池深 100，prefetch 40~50）：

    R 排序类（池内、只是排在 5 名之外）  3 题   ← 调深度/融合**能救**
    G 粒度类（知识被埋在讲别的事的条目里，位次 47~55）  1 题   ← 只能改语料粒度
    M 未匹配（两路都没命中）             1 题   ← 词表/表述差异

最刺眼的一例：问「最高投标限价会公布吗」，支持文档在 **dense 路是第 1 名**，
融合后掉到第 10 名 —— 这是 RRF 的固有行为（两路都出现的中等名次，
其"两路分数之和"会压过只在单路拿第 1 的文档）。
即"召回失手"里有 60% 其实是**排序**问题，而不是"库里没有"或"搜不到"。
"""

from __future__ import annotations

